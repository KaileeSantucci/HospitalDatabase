--table sources, stores the information about each of the 4 hospitals the data comes from
--other tables need to point to sources with a foreign key that's why it is created first
--it is kept in its own table so city and continent are not repeated in every row
CREATE TABLE Sources(
	source_code CHAR(1) PRIMARY KEY, --the code is always 1 letter (CHAR(1)) for each hospital
	city VARCHAR(40) NOT NULL,  --city of where the hospital is (Toronto, paris...)
	continent VARCHAR(40) NOT NULL, --continent of the hospital (North America, Europe...)
	file_format VARCHAR(10) NOT NULL, --original file format of the source(CSV,XML...)
	time_difference_hours SMALLINT NOT NULL --time difference from UTC in hours(-4,2,8,10) done in task2 with the converting dates to UTC 
);

CREATE TABLE Patients (
	--changing 'ALWAYS' to 'BY DEFAULT' bc ALWAYS allows PostgreSQL make up its own id 
	--and doesn't accept the ones we give it (thats why it is changed for every table)
	--BY DEFAULT will make one up if we don't have one
	patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  
	first_name VARCHAR(40) NOT NULL,
	last_name VARCHAR(40) NOT NULL,
	date_of_birth DATE NOT NULL,
	gender VARCHAR(20),
	address VARCHAR(60) NOT NULL,
	telephone_number VARCHAR(15) NOT NULL,
	health_insurance_number VARCHAR(12) NOT NULL UNIQUE,
	emergency_contact_name VARCHAR(40),
	emergency_contact_phone VARCHAR(15),
	life_status VARCHAR(12) NOT NULL
		CHECK (life_status IN ('Alive', 'Deceased')),
	death_datetime TIMESTAMP,
	source_code CHAR(1) NOT NULL,  -- which hospital record comes from (A, B, C, D)
	source_record_id VARCHAR(20) NOT NULL, -- the original id in that hospital, to trace the record back to its source (P00001)
 
	CHECK((life_status = 'Alive' AND death_datetime IS NULL)
			OR (life_status = 'Deceased')),
	FOREIGN KEY (source_code) REFERENCES Sources(source_code), -- the source code must exist in the sources table
	UNIQUE (source_code, source_record_id) -- the same original record cannot be imported 2 times
);

-- table patient source mapping which links each original id from a source to the new integrated patient_id
-- when 2 source records are the same person and get merged then that patient would have many rows here so no original id was lost (mapping 1:N)
--patients are only merged if they have the same health insurance num (our rule)
CREATE TABLE PatientSourceMapping(
	mapping_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, --new id for each row mapping
	source_code CHAR(1) NOT NULL, --which hospital the original patient comes from
	source_patient_id VARCHAR(20) NOT NULL, --the original patient id in that hospital 
	patient_id INTEGER NOT NULL, --the new integrated patient id 

	FOREIGN KEY (source_code) REFERENCES Sources(source_code),
	FOREIGN KEY (patient_id) REFERENCES Patients(patient_id),
	UNIQUE (source_code, source_patient_id) --each original patient id is mapped only 1 time
);

CREATE TABLE Admissions (
	admission_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
	patient_id INTEGER NOT NULL,
	admission_datetime TIMESTAMP NOT NULL,
	admission_type VARCHAR(20) NOT NULL
		CHECK (admission_type IN ('emergency', 'urgent', 'elective', 'outpatient', 'newborn', 'other')),
	admission_source VARCHAR(60),
	reason_for_admission VARCHAR(120),
	insurance_info VARCHAR(100),
	condition_on_admission TEXT,
	admitting_professional VARCHAR(60),
	discharge_datetime TIMESTAMP,
	final_status VARCHAR(20)
		CHECK (final_status IN ('Discharged', 'Deceased', 'Transferred', 'Other')),
	source_code CHAR(1) NOT NULL,  -- which hospital record comes from (A, B, C, D)
	source_record_id VARCHAR(20) NOT NULL, -- the original id in that hospital, to trace the record back to its source 
 

	FOREIGN KEY (patient_id) REFERENCES Patients(patient_id),

	CHECK (discharge_datetime IS NULL
			OR discharge_datetime >= admission_datetime),
	CHECK ((final_status IS NULL AND discharge_datetime IS NULL)
			OR (final_status IS NOT NULL AND discharge_datetime IS NOT NULL)),
	FOREIGN KEY (source_code) REFERENCES Sources(source_code), -- the source code must exist in the sources table
	UNIQUE (source_code, source_record_id) -- the same original record cannot be imported 2 times
);

